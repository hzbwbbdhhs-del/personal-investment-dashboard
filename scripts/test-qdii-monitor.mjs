import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
import { createRequire } from 'node:module';
const require=createRequire(import.meta.url);
const core=require('../'+(existsSync('app.js')?'':'dist/')+'qdii-monitor-core.js');
const now=Date.now(), stamp=new Date(now).toISOString();
const fixture={ code:'000001', name:'测试标普500A', currency:'CNY', category:'sp500', noticeCheckedAt:stamp, latestNotices:[], evidence:{ checkedAt:stamp, noticeDate:'2026-01-01', agency:{ amount:1000 }, direct:{ amount:null } } };
let state=core.track(null,[fixture],now);
assert.equal(state.events.length,0);
assert.equal(state.baseline['000001:agency'].amount,1000);
fixture.evidence.agency.amount=500;
state=core.track(state,[fixture],now+1);
assert.equal(state.events.length,1);
assert.equal(state.events[0].before,1000);
assert.equal(core.track(state,[fixture],now+2).events.length,1);
fixture.evidence.error='network';
fixture.evidence.agency.amount=0;
assert.equal(core.track(state,[fixture],now+3).baseline['000001:agency'].amount,500);
delete fixture.evidence.error;
assert.equal(core.observations([fixture],now+91*60000).length,0);
fixture.latestNotices=[{date:'2026-02-01'}];
assert.equal(core.observations([fixture],now).length,0);
assert.equal(core.comparable({...fixture,name:'大成标普500等权重'}),false);
assert.equal(core.largeChannels(500,600).length,0);
assert.equal(core.largeChannels(1000,null).length,1);
assert.equal(core.largeChannels(null,999).length,0);
assert.equal(core.feeValid({status:'available',checkedAt:stamp,documentDate:stamp.slice(0,10),operatingPct:0},now),true);
assert.equal(core.feeValid({status:'available',checkedAt:stamp,documentDate:stamp.slice(0,10),operatingPct:null},now),false);
const fee={navCheckedAt:stamp, nav:[{date:'2026-10-09',value:2,accumulated:2},{date:'2025-10-09',value:1,accumulated:1}]};
const period={start:'2025-10-09',end:'2026-10-09'};
assert.equal(core.periodReturn(fee,period,now),100);
fee.nav[0].accumulated=3;
assert.equal(core.periodReturn(fee,period,now),null);
const fees={};
const candidates=[0.4,0.2,0.2,0.1,null,0.05].map((cost,i)=>{
  const code=String(i+1).padStart(6,'0');
  fees[code]={status:'available',checkedAt:stamp,documentDate:stamp.slice(0,10),operatingPct:cost};
  return {...fixture,code,name:i===5?'测试标普500等权重A':'测试标普500A',quota:i===3?0:1};
});
candidates.push({...fixture,code:'999999',quota:null},{...fixture,code:'999998',quota:1000,currency:'USD'},{...fixture,code:'999997',quota:1000,exchangeOnly:true});
const ranked=core.purchaseRanking(candidates,fees,f=>({available:f.quota}),now);
assert.deepEqual(ranked.eligible.map(f=>f.code),['000002','000003','000001','000005','000006']);
assert.deepEqual(ranked.ranks,{'000002':1,'000003':1,'000001':3});
fees['000002'].checkedAt='2020-01-01';
assert.equal(core.purchaseRanking(candidates,fees,f=>({available:f.quota}),now).ranks['000002'],undefined);
console.log('PASS: history, evidence, merged positive-quota fee ranking, ties, strategy boundaries and NAV');
